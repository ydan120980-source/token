'use strict';
const CODES = new Set([
  'GITHUB_NOT_CONFIGURED', 'GITHUB_OFFLINE', 'GITHUB_RATE_LIMITED', 'GITHUB_AUTH_REQUIRED', 'GITHUB_FORBIDDEN',
  'GITHUB_REQUEST_FAILED', 'GITHUB_DENIED', 'GITHUB_CODE_EXPIRED', 'GITHUB_SECURE_STORAGE_REQUIRED',
  'GITHUB_REPOSITORY_INVALID', 'GITHUB_NOT_CONNECTED', 'GITHUB_BUSY', 'GITHUB_SYNC_CONFLICT',
]);
const REPOSITORY = /^(?!\.)[A-Za-z0-9_.-]{1,100}\/(?!\.)[A-Za-z0-9_.-]{1,100}$/;
function githubError(code) { return CODES.has(code) ? code : 'GITHUB_REQUEST_FAILED'; }

module.exports = { githubError, REPOSITORY };
