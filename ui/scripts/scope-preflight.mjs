// Writes ui/src/theme/preflight.scoped.css: Tailwind's preflight with every selector limited
// to the React layer (elements marked data-ui-root and the data-ui-portal popup root), so the
// legacy renderer keeps its own element styles. Run after upgrading tailwindcss:
//   node ui/scripts/scope-preflight.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const source = require.resolve("tailwindcss/preflight.css");
const version = require("tailwindcss/package.json").version;
const css = fs.readFileSync(source, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const ROOT = ":where([data-ui-root], [data-ui-portal])";

// html / :host become the roots themselves; universal and pseudo-element-only selectors cover the
// roots and everything inside them; any other selector applies inside the roots.
function scope(selector) {
  const s = selector.trim();
  if (s === "html" || s === ":host") return [ROOT];
  if (s === "*") return [ROOT, ROOT + " *"];
  if (/^::?[a-z-]+(\(.*\))?$/i.test(s)) return [ROOT + s, ROOT + " *" + s];
  return [ROOT + " " + s];
}

function splitSelectors(text) {
  const out = []; let depth = 0, start = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === "(") depth++; else if (c === ")") depth--;
    else if (c === "," && depth === 0) { out.push(text.slice(start, i)); start = i + 1; }
  }
  out.push(text.slice(start));
  return out.map(s => s.trim()).filter(Boolean);
}

// A small block walker: preflight is flat rules plus @supports wrappers.
function walk(text) {
  let out = "", i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    const head = text.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (depth && j < text.length) { if (text[j] === "{") depth++; else if (text[j] === "}") depth--; j++; }
    const body = text.slice(open + 1, j - 1);
    if (head.startsWith("@")) out += head + " {\n" + walk(body) + "}\n";
    else out += splitSelectors(head).flatMap(scope).join(",\n") + " {" + body.replace(/\s+/g, " ").trim().replace(/^/, " ") + " }\n";
    i = j;
  }
  return out;
}

const header = "/* Generated by ui/scripts/scope-preflight.mjs from tailwindcss " + version + " preflight.css (MIT).\n   Do not edit; rerun the script after a tailwindcss upgrade. */\n\n";
fs.writeFileSync(path.join(here, "../src/theme/preflight.scoped.css"), header + walk(css));
console.log("wrote preflight.scoped.css from tailwindcss " + version);
